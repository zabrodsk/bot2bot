// Czech for the dashboard and the login email. English is the source text: tr('Save') gives 'Save' on an English
// page and the Czech entry on a Czech one. To add a string, write it in English with tr('…') (a plain quoted
// literal, so the test can find it) and add the same key to CS below. Placeholders are {name}; values are put in
// as given, so escape them first where the page needs it. Plurals: tr.n(count, 'one|other', vars), with three
// Czech forms [1, 2 to 4, 0 and 5 or more]; {n} is the count. A missing Czech entry falls back to English, and
// test/i18n.test.mjs fails until it is added.
//
// Not translated on purpose: messages people paste into their bots (bots read English), API responses, the CLI.

export const LANGS = ['en', 'cs'];
export const normLang = (v) => (v === 'cs' ? 'cs' : 'en');

// The browser's first choice decides: Czech for cs or sk, English for anything else.
export function langFromHeader(header) {
  const tags = String(header || '').split(',').map((part, i) => {
    const [tag, ...params] = part.trim().split(';');
    const qp = params.map((x) => x.trim()).find((x) => x.startsWith('q='));
    const q = qp ? Number(qp.slice(2)) : 1;
    return { tag: tag.trim().toLowerCase(), q: Number.isFinite(q) ? q : 0, i };
  }).filter((x) => x.tag && x.tag !== '*' && x.q > 0).sort((a, b) => b.q - a.q || a.i - b.i);
  return /^(cs|sk)\b/.test(tags[0]?.tag || '') ? 'cs' : 'en';
}

const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);
const csPlural = new Intl.PluralRules('cs');

const made = new Map();
export function t(lang) {
  lang = normLang(lang);
  if (made.has(lang)) return made.get(lang);
  const dict = lang === 'cs' ? CS : null;
  // A key can start with a [context] when one English word needs two Czech ones ('[noun]Change'); English drops it.
  const tr = (key, vars) => fill(dict && typeof dict[key] === 'string' ? dict[key] : key.replace(/^\[\w+\]/, ''), vars);
  tr.lang = lang;
  tr.locale = lang === 'cs' ? 'cs-CZ' : 'en-GB';
  tr.n = (n, key, vars = {}) => {
    const forms = dict && Array.isArray(dict[key]) ? dict[key] : null;
    const [one, other] = key.split('|');
    const pick = forms ? forms[{ one: 0, few: 1 }[csPlural.select(n)] ?? 2] : n === 1 ? one : other;
    return fill(pick, { n, ...vars });
  };
  tr.date = (ms) => new Date(ms).toLocaleDateString(tr.locale, { day: 'numeric', month: 'long', year: 'numeric' });
  tr.ago = (ms, now) => {
    if (!ms) return tr('never');
    const s = Math.round((now - ms) / 1000);
    if (s < 60) return tr('just now');
    if (s < 3600) return tr('{n} min ago', { n: Math.round(s / 60) });
    if (s < 86400) return tr('{n} h ago', { n: Math.round(s / 3600) });
    return tr.n(Math.round(s / 86400), '{n} d ago|{n} d ago');
  };
  // Text made outside the dashboard (relay errors written for bots, operator settings): known ones in Czech,
  // anything else as it is.
  tr.msg = (text) => {
    const s = String(text ?? '');
    if (!dict) return s;
    // Relay errors reach the page as they are, capitalised, or with a full stop added.
    const low = s.replace(/^\w/, (x) => x.toLowerCase());
    for (const k of [s, low, low.replace(/\.$/, '')]) if (typeof CS_MESSAGES[k] === 'string') return CS_MESSAGES[k];
    for (const [re, to] of CS_PATTERNS) if (re.test(s)) return s.replace(re, to);
    return s;
  };
  made.set(lang, tr);
  return tr;
}

